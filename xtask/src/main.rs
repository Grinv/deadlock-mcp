//! Development tasks. `cargo xtask manifest` and `cargo xtask server-json` write the distribution
//! metadata (see `manifest.rs`).
//!
//! `cargo xtask contracts`: regenerates `src/contracts/{api,valve}.rs` from the pinned upstream
//! contracts in `contracts/` (see `contracts/SOURCES.md`). The output is committed, so building the
//! server needs neither the generators nor the network.

use std::collections::BTreeSet;
use std::error::Error;
use std::fs;
use std::mem::DropGuard;
use std::path::{Path, PathBuf};

use serde_json::Value;

mod manifest;

type Result<T> = std::result::Result<T, Box<dyn Error>>;

/// Deadlock API response schemas the server reads; their dependencies are pulled in.
const API_SCHEMAS: &[&str] = &[
    "Accolade",
    "AnalyticsAbilityOrderStats",
    "AnalyticsHeroStats",
    "Build",
    "EnemyStats",
    "FeedItem",
    "GenericData",
    "Hero",
    "HeroCounterStats",
    "HeroStats",
    "HeroSynergyStats",
    "IngestStatusResponse",
    "Item",
    "ItemFlowStats",
    "ItemStats",
    "KillDeathStats",
    "LaneMatchupStats",
    "LaneSoulCurve",
    "Leaderboard",
    "MapData",
    "MateStats",
    "PlayerMatchHistoryEntry",
    "PlayerPerformanceCurvePoint",
    "PlayerStatsMetrics",
    "Rank",
    "RankResponse",
    "SteamProfile",
];

/// Enums the API declares inline on a parameter: `(path, parameter, type name)`. They are
/// generated as named types deriving `JsonSchema`, with the parameter's description, so tool
/// arguments offer the API's own values.
const API_PARAMS: &[(&str, &str, &str)] = &[
    ("/v1/builds", "build_language", "BuildLanguage"),
    ("/v1/leaderboard/{region}", "region", "Region"),
];

/// Generated types that tool arguments and answers take as they are (the metric names of
/// `PlayerStatsMetrics`, the shop slots), so they derive `JsonSchema` as well.
const API_ARGS: &[&str] = &["ItemSlotType", "PlayerStatsMetricsKey"];

/// The match metadata message and what it imports.
const PROTO_ROOT: &str = "citadel_gcmessages_common.proto";
const PROTO_DIRS: &[&str] = &["deadlock", "common", "gcsdk"];

fn main() -> Result<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .ok_or("xtask lives in the workspace root")?;
    match std::env::args().nth(1).as_deref() {
        Some("contracts") => {
            api(root)?;
            valve(root)
        }
        Some("manifest") => manifest::manifest(root),
        Some("server-json") => {
            manifest::server_json(root, &std::env::args().nth(2).unwrap_or_default())
        }
        Some("npm") => match std::env::args().nth(2) {
            Some(out) => manifest::npm(root, Path::new(&out)),
            None => Err("usage: cargo xtask npm <output dir>".into()),
        },
        _ => Err("usage: cargo xtask contracts|manifest|server-json <sha256>|npm <dir>".into()),
    }
}

fn header(source: &str) -> String {
    format!("// @generated by `cargo xtask contracts` from {source}. Do not edit.\n\n")
}

/// Keeps `date-time` strings as `String`: the server only passes them through, and typify would
/// otherwise need `chrono` at run time.
fn drop_date_time(v: &mut Value) {
    match v {
        Value::Object(m) => {
            if m.get("format").and_then(Value::as_str) == Some("date-time") {
                m.remove("format");
            }
            m.values_mut().for_each(drop_date_time);
        }
        Value::Array(a) => a.iter_mut().for_each(drop_date_time),
        _ => {}
    }
}

/// Names untagged `oneOf` variants after the schema they extend (`allOf: [{$ref: Upgrade}, ..]`),
/// so typify emits `Item::Upgrade` instead of `Item::Variant2`. The variant's `type` tag becomes
/// `UpgradeTag`: typify would call it `UpgradeType`, and a schema of that name may already exist
/// (`AbilityType` does), which typify then reuses for the tag.
fn title_variants(v: &mut Value) {
    match v {
        Value::Object(m) => {
            if let Some(Value::Array(variants)) = m.get_mut("oneOf") {
                for variant in variants.iter_mut() {
                    let name = variant["allOf"][0]["$ref"]
                        .as_str()
                        .and_then(|r| r.rsplit('/').next())
                        .map(str::to_owned);
                    if let Some(name) = name {
                        if let Some(tag) = variant
                            .pointer_mut("/allOf/1/properties/type")
                            .and_then(Value::as_object_mut)
                        {
                            tag.entry("title")
                                .or_insert(Value::String(format!("{name}Tag")));
                        }
                        if let Value::Object(vm) = variant {
                            vm.entry("title").or_insert(Value::String(name));
                        }
                    }
                }
            }
            m.values_mut().for_each(title_variants);
        }
        Value::Array(a) => a.iter_mut().for_each(title_variants),
        _ => {}
    }
}

/// `$ref` names a schema points at.
fn refs(v: &Value, out: &mut BTreeSet<String>) {
    match v {
        Value::Object(m) => {
            for (k, x) in m {
                match (k.as_str(), x.as_str()) {
                    ("$ref", Some(r)) => {
                        out.insert(r.rsplit('/').next().unwrap_or(r).to_owned());
                    }
                    _ => refs(x, out),
                }
            }
        }
        Value::Array(a) => a.iter().for_each(|x| refs(x, out)),
        _ => {}
    }
}

/// `OpenAPI` 3.1 component schemas are JSON Schema; typify turns the needed ones into serde types.
fn api(root: &Path) -> Result<()> {
    let spec: Value =
        serde_json::from_str(&fs::read_to_string(root.join("contracts/openapi.json"))?)?;
    let all = spec["components"]["schemas"]
        .as_object()
        .ok_or("openapi.json has no components.schemas")?;
    let mut keep: BTreeSet<String> = API_SCHEMAS.iter().map(|s| (*s).to_owned()).collect();
    loop {
        let mut more = BTreeSet::new();
        for name in &keep {
            refs(all.get(name).ok_or(format!("no schema {name}"))?, &mut more);
        }
        let before = keep.len();
        keep.extend(more);
        if keep.len() == before {
            break;
        }
    }
    let mut defs: serde_json::Map<String, Value> =
        keep.iter().map(|n| (n.clone(), all[n].clone())).collect();
    let mut settings = typify::TypeSpaceSettings::default();
    for (path, param, name) in API_PARAMS {
        let schema = spec["paths"][path]["get"]["parameters"]
            .as_array()
            .and_then(|ps| ps.iter().find(|p| p["name"] == *param))
            .map(|p| {
                let mut schema = p["schema"].clone();
                if let Some(d) = p.get("description") {
                    schema["description"] = d.clone();
                }
                schema
            })
            .ok_or(format!("no parameter {param} on {path}"))?;
        defs.insert((*name).to_owned(), schema);
        settings.with_patch(
            name,
            typify::TypeSpacePatch::default().with_derive("schemars::JsonSchema"),
        );
    }
    for name in API_ARGS {
        settings.with_patch(
            name,
            typify::TypeSpacePatch::default().with_derive("schemars::JsonSchema"),
        );
    }
    let mut defs = Value::Object(defs);
    drop_date_time(&mut defs);
    title_variants(&mut defs);
    let text = serde_json::to_string(&serde_json::json!({ "$defs": defs }))?
        .replace("#/components/schemas/", "#/$defs/");
    let mut space = typify::TypeSpace::new(&settings);
    space.add_root_schema(serde_json::from_str(&text)?)?;
    let code = prettyplease::unparse(&syn::parse2(space.to_stream()?)?);
    write(root, "api.rs", &(header("contracts/openapi.json") + &code))
}

/// Valve's protobuf messages with serde derives: the Deadlock API serves match metadata as these
/// messages in JSON (`#[serde(default)]` because older matches lack newer fields).
fn valve(root: &Path) -> Result<()> {
    let dirs: Vec<PathBuf> = PROTO_DIRS
        .iter()
        .map(|d| root.join("contracts/protos").join(d))
        .collect();
    let fds = protox::compile([PROTO_ROOT], &dirs)?;
    // Removed however this function returns, a failed generation included.
    let out = DropGuard::new(
        std::env::temp_dir().join(format!("xtask-prost-{}", std::process::id())),
        |dir| {
            let _ = fs::remove_dir_all(dir);
        },
    );
    fs::create_dir_all(&*out)?;
    prost_build::Config::new()
        .out_dir(&*out)
        .type_attribute(".", "#[derive(serde::Deserialize)]")
        .message_attribute(".", "#[serde(default)]")
        .compile_fds(fds)?;
    // The protos declare no package, so prost writes everything to `_.rs`.
    let code = fs::read_to_string(out.join("_.rs"))?;
    write(root, "valve.rs", &(header("contracts/protos") + &code))
}

fn write(root: &Path, file: &str, code: &str) -> Result<()> {
    let path = root.join("src/contracts").join(file);
    fs::write(&path, code)?;
    // The committed files are rustfmt's layout; formatting here keeps a regeneration diff-free.
    let status = std::process::Command::new("rustfmt")
        .args(["--edition", "2024"])
        .arg(&path)
        .status()?;
    if !status.success() {
        return Err(format!("rustfmt failed on {}", path.display()).into());
    }
    println!("wrote {} ({} lines)", path.display(), code.lines().count());
    Ok(())
}
